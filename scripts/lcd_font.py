#!/usr/bin/env python3
"""Generate the ErgoDox Infinity LCD fonts (keyboards/ergodox/lcd_font.h) from DejaVu Sans Mono.

    python3 scripts/lcd_font.py > keyboards/ergodox/lcd_font.h

Needs Pillow and the DejaVu fonts (fonts-dejavu-core), which the devcontainer has; `just ergodox-lcd-font`
runs it. Each font is monospaced: every printable ASCII character (space to ~) is a cell of `width`
columns, and each column is a uint16_t with bit 0 at the top. The glyphs are rendered without
anti-aliasing, as the LCD only has black and white pixels.

DejaVu fonts are free to use and embed (Bitstream Vera Fonts copyright, with DejaVu changes in the
public domain): https://dejavu-fonts.github.io/License.html
"""

import sys

from PIL import Image, ImageDraw, ImageFont

FONT_DIR = "/usr/share/fonts/truetype/dejavu"

# name, file, pixel size, cell width (columns per character)
FONTS = [
    ("lcd_font_large", "DejaVuSansMono-Bold.ttf", 12, 8),
    ("lcd_font_small", "DejaVuSansMono-Bold.ttf", 8, 6),
]

FIRST, LAST = 0x20, 0x7E


def render(path, size, width):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    if height > 16:
        raise SystemExit(f"{path} at {size}px is {height} rows; columns are 16 bits")
    glyphs = []
    for code in range(FIRST, LAST + 1):
        # Render wider than the cell to catch glyphs that would be clipped.
        img = Image.new("1", (width + 4, height), 0)
        draw = ImageDraw.Draw(img)
        draw.fontmode = "1"
        draw.text((0, 0), chr(code), font=font, fill=1)
        for x in range(width, width + 4):
            if any(img.getpixel((x, y)) for y in range(height)):
                raise SystemExit(f"{chr(code)!r} in {path} at {size}px is wider than {width} columns")
        cols = []
        for x in range(width):
            bits = 0
            for y in range(height):
                if img.getpixel((x, y)):
                    bits |= 1 << y
            cols.append(bits)
        glyphs.append(cols)
    return height, glyphs


def main():
    out = [
        "/* Generated by scripts/lcd_font.py from DejaVu Sans Mono; don't edit by hand. */",
        "/* DejaVu fonts: Bitstream Vera Fonts copyright, DejaVu changes in the public domain. */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    uint8_t         width;  // columns per character",
        "    uint8_t         height; // rows",
        "    uint8_t         first;  // first character",
        "    uint8_t         last;   // last character",
        "    const uint16_t *columns;",
        "} lcd_font_t;",
    ]
    for name, file, size, width in FONTS:
        height, glyphs = render(f"{FONT_DIR}/{file}", size, width)
        out += ["", f"// {file}, {size} px: {width} x {height}", f"static const uint16_t {name}_columns[] = {{"]
        for code, cols in zip(range(FIRST, LAST + 1), glyphs):
            label = "space" if code == 0x20 else ("backslash" if chr(code) == "\\" else chr(code))
            out.append("    " + ", ".join(f"0x{c:04x}" for c in cols) + f", // {label}")
        out += [
            "};",
            f"static const lcd_font_t {name} = {{{width}, {height}, 0x{FIRST:02x}, 0x{LAST:02x}, {name}_columns}};",
        ]
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
